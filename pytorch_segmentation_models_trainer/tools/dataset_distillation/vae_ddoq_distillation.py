# -*- coding: utf-8 -*-
"""VAE-backed DDOQ image distillation pipeline.

The pipeline encodes every input image with a trained VAE, clusters the latent
embeddings with Mini-Batch K-Means, decodes one image per cluster center, and
writes two Parquet manifests:

.. code-block:: yaml

    dataset_distillation:
      k: 500
      vae_config_path: conf/vae.yaml
      vae_checkpoint_path: runs/vae.ckpt
      output_dir: outputs/ddoq
      distilled_image_format: auto
      latent: mu
      latent_reduction: flatten
      weight_mode: sqrt
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence, Tuple, Union

import pandas as pd
import torch
from hydra.utils import get_class, instantiate
from omegaconf import DictConfig, OmegaConf
from PIL import Image
from torch.utils.data import DataLoader
from tqdm import tqdm

from pytorch_segmentation_models_trainer.dataset_distillation import (
    KMeansClusteringTool,
)
from pytorch_segmentation_models_trainer.dataset_loader.dataset import _worker_init_fn

PathLike = Union[str, Path]


@dataclass
class VaeDdoqDistillationResult:
    """Artifacts produced by :class:`VaeDdoqDistillationPipeline`.

    Args:
        embeddings: Flattened input image embeddings with shape ``(N, D)``.
        cluster_centers: K-Means centroids with shape ``(K, D)``.
        cluster_labels: Cluster id for each input image with shape ``(N,)``.
        weights: DDOQ cluster weights with shape ``(K,)``.
        embeddings_parquet_path: Path to the input embedding Parquet file.
        distilled_images_parquet_path: Path to the distilled image Parquet file.
        distilled_image_paths: Paths to decoded cluster-center images.

    Returns:
        Dataclass with tensors and file paths generated by the run.
    """

    embeddings: torch.Tensor
    cluster_centers: torch.Tensor
    cluster_labels: torch.Tensor
    weights: torch.Tensor
    embeddings_parquet_path: Path
    distilled_images_parquet_path: Path
    distilled_image_paths: List[Path]


def _flatten_embedding(
    embedding: torch.Tensor, reduction: str = "flatten"
) -> torch.Tensor:
    """Convert VAE latents to a 2-D matrix suitable for K-Means.

    Args:
        embedding: Tensor with shape ``(B, D)``, ``(B, L, D)``, or
            ``(B, C, H, W)``.
        reduction: ``"flatten"`` preserves all latent positions by flattening
            non-batch dimensions. ``"mean_spatial"`` averages spatial/sequence
            positions before returning one vector per image.

    Returns:
        Float tensor with shape ``(B, D_flat)``.
    """
    if reduction not in {"flatten", "mean_spatial"}:
        raise ValueError("latent_reduction must be 'flatten' or 'mean_spatial'.")
    if embedding.ndim == 2:
        return embedding.float()
    if reduction == "flatten":
        return embedding.flatten(start_dim=1).float()
    if embedding.ndim == 4:
        return embedding.mean(dim=(2, 3)).float()
    if embedding.ndim == 3:
        return embedding.mean(dim=1).float()
    raise ValueError(f"Unsupported embedding shape: {tuple(embedding.shape)}")


def _extract_batch_images(batch) -> torch.Tensor:
    """Return image tensor from common dataset batch formats."""
    if isinstance(batch, dict):
        image = batch.get("image")
        if image is None:
            image = batch.get("x")
    elif isinstance(batch, (list, tuple)):
        image = batch[0]
    else:
        image = batch
    if image is None:
        raise ValueError("Could not extract image from batch.")
    return image


def _extract_batch_paths(batch, batch_size: int, start_idx: int) -> List[str]:
    """Return absolute image paths from batch metadata or synthetic ids."""
    paths = None
    if isinstance(batch, dict):
        for key in ("path", "image_path", "image_paths", "filename", "file_path"):
            if key in batch:
                paths = batch[key]
                break
    if paths is None:
        return [
            str(Path(f"sample_{start_idx + i}").resolve()) for i in range(batch_size)
        ]
    if isinstance(paths, (str, Path)):
        values = [paths]
    else:
        values = list(paths)
    return [str(Path(str(path)).resolve()) for path in values]


def _resolve_output_format(fmt: str, input_paths: Sequence[str]) -> str:
    """Resolve distilled image extension from config and input images.

    Args:
        fmt: ``"auto"``, ``"tif"``, ``"png"``, ``"jpg"``, or ``"pt"``.
        input_paths: Input image paths used when ``fmt="auto"``.

    Returns:
        Normalized format string without leading dot.
    """
    fmt = (fmt or "auto").lower().lstrip(".")
    if fmt == "auto":
        if not input_paths:
            raise ValueError("Cannot infer distilled image format without input paths.")
        suffix = Path(input_paths[0]).suffix.lower().lstrip(".")
        fmt = "tif" if suffix == "tiff" else suffix
    if fmt not in {"tif", "png", "jpg", "jpeg", "pt"}:
        raise ValueError(
            "Unsupported distilled_image_format. Use auto, tif, png, jpg, jpeg, or pt."
        )
    return "jpg" if fmt == "jpeg" else fmt


def _tensor_to_uint8_image(tensor: torch.Tensor) -> torch.Tensor:
    """Convert one decoded image tensor ``(C, H, W)`` to uint8 for PIL."""
    tensor = tensor.detach().cpu().float()
    if tensor.ndim != 3:
        raise ValueError(f"Expected image tensor (C, H, W), got {tuple(tensor.shape)}.")
    tensor = tensor.clamp(0.0, 1.0)
    return (tensor * 255.0).round().to(torch.uint8)


def _save_decoded_image(tensor: torch.Tensor, path: Path, fmt: str) -> None:
    """Save one decoded tensor as ``pt`` or a common image format.

    Args:
        tensor: Image tensor with shape ``(C, H, W)``.
        path: Destination file path.
        fmt: Normalized format string.

    Returns:
        ``None``.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "pt":
        torch.save(tensor.detach().cpu(), path)
        return

    image = _tensor_to_uint8_image(tensor)
    channels = image.shape[0]
    if channels == 1:
        arr = image.squeeze(0).numpy()
        mode = "L"
    elif channels in {3, 4}:
        arr = image.permute(1, 2, 0).numpy()
        mode = "RGB" if channels == 3 else "RGBA"
    else:
        if fmt in {"png", "jpg"}:
            raise ValueError(
                f"Cannot save {channels}-channel tensor as {fmt}. Use tif or pt."
            )
        arr = image.permute(1, 2, 0).numpy()
        mode = None
    pil_image = Image.fromarray(arr, mode=mode)
    pil_image.save(path)


def _rows_from_tensor(
    tensor: torch.Tensor,
) -> List[List[float]]:
    """Convert a 2-D tensor to Parquet-friendly Python float lists."""
    return tensor.detach().cpu().float().tolist()


def write_embeddings_parquet(
    image_paths: Sequence[str],
    embeddings: torch.Tensor,
    cluster_ids: torch.Tensor,
    output_path: PathLike,
) -> Path:
    """Write input-image embeddings and their assigned cluster ids.

    Args:
        image_paths: Absolute paths for all encoded input images.
        embeddings: Embedding tensor with shape ``(N, D)``.
        cluster_ids: Cluster ids with shape ``(N,)``.
        output_path: Destination Parquet path.

    Returns:
        Path to written Parquet file.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(
        {
            "image_path": list(image_paths),
            "embedding": _rows_from_tensor(embeddings),
            "cluster_id": cluster_ids.detach().cpu().long().tolist(),
        }
    )
    df.to_parquet(output_path, index=False)
    return output_path


def write_distilled_images_parquet(
    distilled_image_paths: Sequence[str],
    cluster_ids: torch.Tensor,
    cluster_embeddings: torch.Tensor,
    weights: torch.Tensor,
    output_path: PathLike,
) -> Path:
    """Write distilled-image manifest with one row per cluster center.

    Args:
        distilled_image_paths: Saved decoded image paths.
        cluster_ids: Cluster ids with shape ``(K,)``.
        cluster_embeddings: Center embeddings with shape ``(K, D)``.
        weights: DDOQ cluster weights with shape ``(K,)``.
        output_path: Destination Parquet path.

    Returns:
        Path to written Parquet file.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(
        {
            "distilled_image_path": [
                str(Path(path).resolve()) for path in distilled_image_paths
            ],
            "cluster_id": cluster_ids.detach().cpu().long().tolist(),
            "cluster_embedding": _rows_from_tensor(cluster_embeddings),
            "weight": weights.detach().cpu().float().tolist(),
        }
    )
    df.to_parquet(output_path, index=False)
    return output_path


class VaeDdoqDistillationPipeline:
    """Run DDOQ image distillation from a trained VAE.

    Args:
        vae: Module exposing ``encode(x)`` and ``decode(z, output_size)``.
        dataloader: DataLoader over input images. Batches may be dicts with
            ``image`` and ``path`` keys, tuples where first item is image, or
            image tensors directly.
        output_dir: Directory where images, Parquets, and tensor artifacts are
            written.
        k: Number of distilled images / clusters.
        device: Torch device for encoding, clustering, and decoding.
        latent: VAE latent tensor to cluster: ``"mu"`` or ``"z"``.
        latent_reduction: ``"flatten"`` or ``"mean_spatial"``.
        weight_mode: ``"density"``, ``"sqrt"``, or ``"uniform"``.
        distilled_image_format: ``"auto"``, ``"tif"``, ``"png"``, ``"jpg"``,
            or ``"pt"``.
        output_size: Optional decoded image size ``(H, W)``. Defaults to first
            input batch size.
        kmeans_max_iter: Maximum Mini-Batch K-Means iterations.
        kmeans_batch_size: Mini-batch size used by K-Means.
        random_seed: Seed passed to Mini-Batch K-Means.
        **kwargs: Ignored compatibility kwargs for Hydra.

    Returns:
        :class:`VaeDdoqDistillationResult` from :meth:`run`.
    """

    def __init__(
        self,
        vae: torch.nn.Module,
        dataloader: DataLoader,
        output_dir: PathLike,
        k: int,
        device: Union[str, torch.device] = "cuda",
        latent: str = "mu",
        latent_reduction: str = "flatten",
        weight_mode: str = "sqrt",
        distilled_image_format: str = "auto",
        output_size: Optional[Tuple[int, int]] = None,
        kmeans_max_iter: int = 100,
        kmeans_batch_size: int = 1024,
        random_seed: Optional[int] = 42,
        **kwargs,
    ) -> None:
        self.vae = vae
        self.dataloader = dataloader
        self.output_dir = Path(output_dir)
        self.k = k
        self.device = torch.device(device)
        self.latent = latent
        self.latent_reduction = latent_reduction
        self.weight_mode = weight_mode
        self.distilled_image_format = distilled_image_format
        self.output_size = output_size
        self.kmeans_max_iter = kmeans_max_iter
        self.kmeans_batch_size = kmeans_batch_size
        self.random_seed = random_seed

    def _encode_all(self) -> Tuple[torch.Tensor, List[str], Tuple[int, int]]:
        self.vae.to(self.device)
        self.vae.eval()
        embeddings = []
        image_paths: List[str] = []
        output_size = self.output_size
        seen = 0

        with torch.no_grad():
            for batch in tqdm(self.dataloader, desc="Extracting VAE embeddings"):
                images = _extract_batch_images(batch).to(self.device)
                if output_size is None:
                    output_size = tuple(images.shape[-2:])
                paths = _extract_batch_paths(batch, images.shape[0], seen)
                mu, logvar = self.vae.encode(images)
                if self.latent == "mu":
                    latent_tensor = mu
                elif self.latent == "z":
                    std = torch.exp(0.5 * logvar)
                    latent_tensor = mu + torch.randn_like(std) * std
                else:
                    raise ValueError("latent must be 'mu' or 'z'.")
                embeddings.append(
                    _flatten_embedding(latent_tensor, self.latent_reduction).cpu()
                )
                image_paths.extend(paths)
                seen += images.shape[0]

        if not embeddings:
            raise ValueError("No embeddings were extracted from the dataloader.")
        return torch.cat(embeddings, dim=0), image_paths, output_size

    def _cluster(
        self, embeddings: torch.Tensor
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        if self.k <= 0:
            raise ValueError("k must be positive.")
        if self.k > embeddings.shape[0]:
            raise ValueError("k must be <= number of embeddings.")
        tool = KMeansClusteringTool(
            n_clusters=self.k,
            device=self.device,
            random_state=self.random_seed or 42,
        )
        tool.fit(
            embeddings,
            batch_size=self.kmeans_batch_size,
            max_iter=self.kmeans_max_iter,
        )
        labels = tool.predict(embeddings).cpu()
        weights = tool.get_cluster_weights(self.weight_mode, labels=labels)
        return tool.model.centroids.detach().cpu(), labels, weights

    def _decode_centers(
        self,
        centers: torch.Tensor,
        output_size: Tuple[int, int],
        image_paths: Sequence[str],
    ) -> List[Path]:
        fmt = _resolve_output_format(self.distilled_image_format, image_paths)
        suffix = "tif" if fmt == "tif" else fmt
        out_dir = self.output_dir / "distilled_images"
        saved_paths: List[Path] = []
        self.vae.to(self.device)
        self.vae.eval()

        with torch.no_grad():
            for start in range(0, centers.shape[0], self.kmeans_batch_size):
                end = min(start + self.kmeans_batch_size, centers.shape[0])
                batch = centers[start:end].to(self.device)
                decoded = self.vae.decode(batch, output_size).detach().cpu()
                for offset, image in enumerate(decoded):
                    cluster_id = start + offset
                    path = out_dir / f"cluster_{cluster_id:06d}.{suffix}"
                    _save_decoded_image(image, path, fmt)
                    saved_paths.append(path.resolve())
        return saved_paths

    def _save_tensor_artifacts(
        self,
        embeddings: torch.Tensor,
        centers: torch.Tensor,
        labels: torch.Tensor,
        weights: torch.Tensor,
    ) -> None:
        torch.save(embeddings, self.output_dir / "embeddings.pt")
        torch.save(centers, self.output_dir / "cluster_centers.pt")
        torch.save(labels, self.output_dir / "cluster_labels.pt")
        torch.save(weights, self.output_dir / "cluster_weights.pt")

    def _save_manifest(self, result: VaeDdoqDistillationResult, output_size) -> None:
        manifest = {
            "k": self.k,
            "latent": self.latent,
            "latent_reduction": self.latent_reduction,
            "weight_mode": self.weight_mode,
            "distilled_image_format": self.distilled_image_format,
            "output_size": list(output_size),
            "embeddings_shape": list(result.embeddings.shape),
            "cluster_centers_shape": list(result.cluster_centers.shape),
            "embeddings_parquet_path": str(result.embeddings_parquet_path),
            "distilled_images_parquet_path": str(result.distilled_images_parquet_path),
        }
        with (self.output_dir / "manifest.json").open("w") as f:
            json.dump(manifest, f, indent=2)

    def run(self) -> VaeDdoqDistillationResult:
        """Execute encode, cluster, decode, and artifact writing.

        Returns:
            Dataclass containing tensors and output paths.
        """
        self.output_dir.mkdir(parents=True, exist_ok=True)
        embeddings, image_paths, output_size = self._encode_all()
        centers, labels, weights = self._cluster(embeddings)
        distilled_paths = self._decode_centers(centers, output_size, image_paths)

        embeddings_parquet = write_embeddings_parquet(
            image_paths=image_paths,
            embeddings=embeddings,
            cluster_ids=labels,
            output_path=self.output_dir / "embeddings.parquet",
        )
        distilled_parquet = write_distilled_images_parquet(
            distilled_image_paths=[str(path) for path in distilled_paths],
            cluster_ids=torch.arange(self.k),
            cluster_embeddings=centers,
            weights=weights,
            output_path=self.output_dir / "distilled_images.parquet",
        )
        self._save_tensor_artifacts(embeddings, centers, labels, weights)
        result = VaeDdoqDistillationResult(
            embeddings=embeddings,
            cluster_centers=centers,
            cluster_labels=labels,
            weights=weights,
            embeddings_parquet_path=embeddings_parquet,
            distilled_images_parquet_path=distilled_parquet,
            distilled_image_paths=distilled_paths,
        )
        self._save_manifest(result, output_size)
        return result


def _as_config_node(cfg: DictConfig) -> DictConfig:
    if "dataset_distillation" in cfg:
        return cfg.dataset_distillation
    return cfg


def load_vae_from_checkpoint(
    config_path: PathLike,
    checkpoint_path: PathLike,
    device: Union[str, torch.device] = "cuda",
) -> torch.nn.Module:
    """Load trained VAE module from a Lightning checkpoint.

    Args:
        config_path: YAML used to train the VAE. It must include ``pl_model``
            and ``model`` entries.
        checkpoint_path: Lightning ``.ckpt`` path.
        device: Device where returned VAE module is moved.

    Returns:
        Inner VAE module exposing ``encode`` and ``decode``.
    """
    cfg = OmegaConf.load(config_path)
    OmegaConf.resolve(cfg)
    pl_model_target = cfg.get(
        "pl_model",
        {
            "_target_": (
                "pytorch_segmentation_models_trainer.model_loader."
                "variational_autoencoder_model.VariationalAutoencoderModel"
            )
        },
    )["_target_"]
    pl_model_cls = get_class(pl_model_target)
    lightning_model = pl_model_cls.load_from_checkpoint(
        checkpoint_path,
        cfg=cfg,
        inference_mode=True,
        weights_only=False,
        map_location=device,
    )
    vae = getattr(lightning_model, "model", lightning_model)
    return vae.to(device).eval()


def build_dataloader_from_config(
    config_path: PathLike,
    dataset_key: str = "train_dataset",
    batch_size: Optional[int] = None,
    num_workers: Optional[int] = None,
    seed: Optional[int] = None,
) -> DataLoader:
    """Instantiate dataset and dataloader from a Hydra YAML file.

    Args:
        config_path: YAML containing the dataset config.
        dataset_key: Top-level dataset key, e.g. ``"train_dataset"``.
        batch_size: Optional DataLoader batch size override.
        num_workers: Optional worker count override.
        seed: Optional seed forwarded to dataset constructors.

    Returns:
        DataLoader with ``shuffle=False`` for stable image-to-row ordering.
    """
    cfg = OmegaConf.load(config_path)
    OmegaConf.resolve(cfg)
    if dataset_key not in cfg:
        raise KeyError(f"Dataset key '{dataset_key}' not found in {config_path}.")
    dataset_cfg = cfg[dataset_key]
    dataset = instantiate(dataset_cfg, seed=seed, _recursive_=False)
    data_loader_cfg = dataset_cfg.get("data_loader", {})
    resolved_batch_size = batch_size or data_loader_cfg.get("batch_size", 1)
    resolved_num_workers = (
        num_workers
        if num_workers is not None
        else data_loader_cfg.get("num_workers", 0)
    )
    return DataLoader(
        dataset,
        batch_size=resolved_batch_size,
        shuffle=False,
        num_workers=resolved_num_workers,
        pin_memory=data_loader_cfg.get("pin_memory", False),
        drop_last=False,
        worker_init_fn=_worker_init_fn,
    )


def run_vae_ddoq_from_config(cfg: DictConfig) -> VaeDdoqDistillationResult:
    """Run VAE DDOQ distillation from an OmegaConf config.

    Args:
        cfg: Config with a ``dataset_distillation`` section or the section
            contents directly.

    Returns:
        Pipeline result containing tensor outputs and file paths.
    """
    distill_cfg = _as_config_node(cfg)
    k = int(distill_cfg.get("k", distill_cfg.get("num_clusters", 100)))
    vae_config_path = distill_cfg.get("vae_config_path", None)
    vae_checkpoint_path = distill_cfg.get(
        "vae_checkpoint_path", distill_cfg.get("checkpoint_path", None)
    )
    if vae_config_path is None:
        raise ValueError("dataset_distillation.vae_config_path is required.")
    if vae_checkpoint_path is None:
        raise ValueError("dataset_distillation.vae_checkpoint_path is required.")

    dataset_config_path = distill_cfg.get("dataset_config_path", vae_config_path)
    seed = distill_cfg.get("random_seed", 42)
    device = distill_cfg.get("device", "cuda")
    vae = load_vae_from_checkpoint(vae_config_path, vae_checkpoint_path, device=device)
    dataloader = build_dataloader_from_config(
        dataset_config_path,
        dataset_key=distill_cfg.get("dataset_key", "train_dataset"),
        batch_size=distill_cfg.get("batch_size", None),
        num_workers=distill_cfg.get("num_workers", None),
        seed=seed,
    )
    pipeline = VaeDdoqDistillationPipeline(
        vae=vae,
        dataloader=dataloader,
        output_dir=distill_cfg.get("output_dir", "ddoq_output"),
        k=k,
        device=device,
        latent=distill_cfg.get("latent", "mu"),
        latent_reduction=distill_cfg.get("latent_reduction", "flatten"),
        weight_mode=distill_cfg.get(
            "weight_mode",
            "sqrt" if distill_cfg.get("use_sqrt_heuristic", True) else "density",
        ),
        distilled_image_format=distill_cfg.get("distilled_image_format", "auto"),
        output_size=distill_cfg.get("output_size", None),
        kmeans_max_iter=distill_cfg.get("kmeans_max_iter", 100),
        kmeans_batch_size=distill_cfg.get("kmeans_batch_size", 1024),
        random_seed=seed,
    )
    return pipeline.run()


def run_vae_ddoq_from_config_file(
    yaml_path: PathLike,
    k: Optional[int] = None,
    checkpoint_path: Optional[PathLike] = None,
    output_dir: Optional[PathLike] = None,
    distilled_image_format: Optional[str] = None,
) -> VaeDdoqDistillationResult:
    """Load YAML config, apply CLI overrides, and run VAE DDOQ.

    Args:
        yaml_path: DDOQ YAML path.
        k: Optional cluster-count override.
        checkpoint_path: Optional VAE checkpoint override.
        output_dir: Optional output directory override.
        distilled_image_format: Optional saved image format override.

    Returns:
        Pipeline result.
    """
    cfg = OmegaConf.load(yaml_path)
    if "dataset_distillation" not in cfg:
        cfg = OmegaConf.create({"dataset_distillation": cfg})
    if k is not None:
        cfg.dataset_distillation.k = int(k)
        cfg.dataset_distillation.num_clusters = int(k)
    if checkpoint_path is not None:
        cfg.dataset_distillation.vae_checkpoint_path = str(checkpoint_path)
    if output_dir is not None:
        cfg.dataset_distillation.output_dir = str(output_dir)
    if distilled_image_format is not None:
        cfg.dataset_distillation.distilled_image_format = distilled_image_format
    return run_vae_ddoq_from_config(cfg)
